import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { curriculum } from '../src/data/curriculum.js';

// The leaderboard awards XP server-side from public.lesson_xp_rewards, so that
// table must list every lesson. Run this after adding or re-pricing lessons and
// apply the output in the Supabase SQL editor (it is safe to re-run).

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUTPUT_PATH = resolve(ROOT, 'supabase', 'lesson_xp_rewards.sql');

// Must match the client default in Lesson.jsx (`currentLesson.xpReward || 10`).
const DEFAULT_XP_REWARD = 10;

function sqlString(value) {
    return `'${String(value).replaceAll("'", "''")}'`;
}

const lessons = curriculum.flatMap((module) => module.lessons);
const values = lessons
    .map((lesson) => `    (${sqlString(lesson.id)}, ${lesson.xpReward || DEFAULT_XP_REWARD})`)
    .join(',\n');

const sql = `-- Generated by scripts/generate-lesson-xp-sql.mjs. Do not edit by hand.
insert into public.lesson_xp_rewards (lesson_id, xp)
values
${values}
on conflict (lesson_id) do update set xp = excluded.xp;
`;

await writeFile(OUTPUT_PATH, sql, 'utf8');
console.log(`Generated XP rewards for ${lessons.length} lessons at ${OUTPUT_PATH}`);
